-- PG 版：与 mysql V001 语义对齐（TIMESTAMPTZ/BIGINT 有符号/JSONB/独立索引语句）
-- iam-service PostgreSQL V001 — 与 mysql/V001__init.sql 版本号与表结构对齐。
--
-- 转换规则（设计文档 §3 方言差异归属表，与 config / audit / notification 样板一致）：
--   DATETIME / DATETIME(3)  -> TIMESTAMPTZ / TIMESTAMPTZ(3)  （**不是** TIMESTAMP，
--                              否则 Rust 侧 DateTime Utc 类型无法解码）
--   BOOLEAN / TRUE / FALSE  -> 原样保留（PG 原生 BOOLEAN）
--   JSON                    -> JSONB（envelope_json 由 outbox 库层绑 serde_json::Value，
--                              sqlx-postgres 以 JSONB 编码，与 notification V001 同款）
--   AUTO_INCREMENT + PRIMARY KEY -> BIGINT GENERATED BY DEFAULT AS IDENTITY
--                              （BY DEFAULT 允许显式插 id，保持 MySQL AUTO_INCREMENT 语义）
--   表内 UNIQUE KEY / KEY    -> 独立 CREATE UNIQUE INDEX / CREATE INDEX（均带 IF NOT EXISTS）
--   列级 UNIQUE（username / code / token_hash）保留内联写法，PG 自动命名约束为
--       iam_users_username_key / iam_roles_code_key / iam_org_units_code_key /
--       iam_permissions_code_key / iam_menus_code_key / iam_refresh_tokens_token_hash_key，
--       V003 / V004 按这些名字 DROP CONSTRAINT，换成租户维度的复合唯一索引
--
-- ⚠️ 迁移执行器先按 ASCII 分号切分、再剥离 -- 注释行，因此注释里不能出现 ASCII 分号，
--   且禁止 dollar-quote 定界符 / DO 块 / CREATE FUNCTION / CREATE TRIGGER（本文件已避免）。

CREATE TABLE IF NOT EXISTS iam_users (
    id VARCHAR(36) PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(255),
    phone VARCHAR(20),
    password_hash VARCHAR(255) NOT NULL,
    salt VARCHAR(64) NOT NULL,
    nickname VARCHAR(100) NOT NULL,
    avatar VARCHAR(255),
    status VARCHAR(20) NOT NULL DEFAULT 'active',
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    phone_verified BOOLEAN NOT NULL DEFAULT FALSE,
    last_login_at TIMESTAMPTZ,
    last_login_ip VARCHAR(50),
    password_expired_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS iam_roles (
    id VARCHAR(36) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    code VARCHAR(50) NOT NULL UNIQUE,
    description TEXT,
    data_scope VARCHAR(20) NOT NULL DEFAULT 'self',
    status VARCHAR(20) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS iam_permissions (
    id VARCHAR(36) PRIMARY KEY,
    code VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    category VARCHAR(20) NOT NULL,
    resource VARCHAR(255),
    action VARCHAR(50),
    sort_order INT NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'enabled',
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS iam_menus (
    id VARCHAR(36) PRIMARY KEY,
    parent_id VARCHAR(36),
    name VARCHAR(100) NOT NULL,
    code VARCHAR(100) NOT NULL UNIQUE,
    path VARCHAR(255) NOT NULL,
    component VARCHAR(255),
    icon VARCHAR(100),
    sort_order INT NOT NULL DEFAULT 0,
    visible BOOLEAN NOT NULL DEFAULT TRUE,
    status VARCHAR(20) NOT NULL DEFAULT 'enabled',
    permission_id VARCHAR(36),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_at TIMESTAMPTZ,
    FOREIGN KEY (parent_id) REFERENCES iam_menus(id),
    FOREIGN KEY (permission_id) REFERENCES iam_permissions(id)
);

CREATE TABLE IF NOT EXISTS iam_org_units (
    id VARCHAR(36) PRIMARY KEY,
    parent_id VARCHAR(36),
    name VARCHAR(100) NOT NULL,
    code VARCHAR(50) NOT NULL UNIQUE,
    level INT NOT NULL DEFAULT 1,
    sort_order INT NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_at TIMESTAMPTZ,
    FOREIGN KEY (parent_id) REFERENCES iam_org_units(id)
);

CREATE TABLE IF NOT EXISTS iam_user_roles (
    user_id VARCHAR(36) NOT NULL,
    role_id VARCHAR(36) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (user_id, role_id),
    FOREIGN KEY (user_id) REFERENCES iam_users(id),
    FOREIGN KEY (role_id) REFERENCES iam_roles(id)
);

CREATE TABLE IF NOT EXISTS iam_role_permissions (
    role_id VARCHAR(36) NOT NULL,
    permission_id VARCHAR(36) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (role_id, permission_id),
    FOREIGN KEY (role_id) REFERENCES iam_roles(id),
    FOREIGN KEY (permission_id) REFERENCES iam_permissions(id)
);

CREATE TABLE IF NOT EXISTS iam_user_org_units (
    user_id VARCHAR(36) NOT NULL,
    org_unit_id VARCHAR(36) NOT NULL,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (user_id, org_unit_id),
    FOREIGN KEY (user_id) REFERENCES iam_users(id),
    FOREIGN KEY (org_unit_id) REFERENCES iam_org_units(id)
);

CREATE TABLE IF NOT EXISTS iam_refresh_tokens (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    client_ip VARCHAR(50) NOT NULL,
    user_agent TEXT,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    FOREIGN KEY (user_id) REFERENCES iam_users(id)
);

CREATE TABLE IF NOT EXISTS iam_login_logs (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36),
    username VARCHAR(50) NOT NULL,
    ip_address VARCHAR(50) NOT NULL,
    user_agent TEXT,
    location VARCHAR(100),
    login_type VARCHAR(20) NOT NULL,
    success BOOLEAN NOT NULL,
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    FOREIGN KEY (user_id) REFERENCES iam_users(id)
);

-- Outbox table for iam-service domain events (Phase 4 event bus).
-- iam-service writes here in the same transaction as the business row,
-- and the iam-outbox-publisher binary polls and publishes to RabbitMQ.
-- envelope_json 用 JSONB：与 iam_outbox_events_archive（V002）及
-- libs/common-event outbox_archive.rs 的 PG 臂读写路径保持同一类型。
CREATE TABLE IF NOT EXISTS iam_outbox_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    event_id        CHAR(36)     NOT NULL,
    event_type      VARCHAR(128) NOT NULL,
    routing_key     VARCHAR(128) NOT NULL,
    envelope_json   JSONB        NOT NULL,
    created_at      TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    published_at    TIMESTAMPTZ(3) NULL,
    PRIMARY KEY (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_iam_outbox_event_id ON iam_outbox_events (event_id);

CREATE INDEX IF NOT EXISTS idx_iam_outbox_unpublished ON iam_outbox_events (published_at, id);
