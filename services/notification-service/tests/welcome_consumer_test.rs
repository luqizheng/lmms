/// One Redis container reused across all 3 welcome tests in this binary so we
/// don't pay the testcontainers cold-start cost three times. Container lives
/// for the process lifetime (kept inside the static fixture).
struct RedisFixture {
    _container: testcontainers::ContainerAsync<Redis>,
    cli: RedisCli,
}

static REDIS: OnceCell<RedisFixture> = OnceCell::const_new();

async fn redis_cli() -> RedisCli {
    REDIS
        .get_or_init(|| async {
            let c = Redis::default().start().await.unwrap();
            let host = c.get_host().await.unwrap();
            let port = c.get_host_port_ipv4(6379).await.unwrap();
            let url = format!("redis://{host}:{port}");
            let cli = RedisCli::connect(&url).await.unwrap();
            RedisFixture {
                _container: c,
                cli,
            }
        })
        .await
        .cli
        .clone()
}

fn payload(user_id: &str, username: &str) -> IamUserCreated {
    IamUserCreated {
        user_id: user_id.to_string(),
        username: username.to_string(),
        email: None,
        org_unit_id: None,
    }
}

/// Count outbox rows whose envelope_json.payload.announcement_id equals `ann_id`.
/// Mirrors the `outbox_count` helper in announcement_publish_test.rs: the
/// event_id of the outbox row is generated by `Envelope::new`, NOT the iam
/// event_id, so we filter on the announcement_id inside the payload.
async fn outbox_count_for_announcement(db: &Db, ann_id: u64) -> i64 {
    let (n,): (i64,) = sqlx::query_as(
        "SELECT COUNT(*) FROM ntf_outbox_events \
         WHERE event_type = 'notification.announcement.published' \
         AND JSON_EXTRACT(envelope_json, '$.payload.announcement_id') = ?",
    )
    .bind(ann_id as i64)
    .fetch_one(&db.pool)
    .await
    .unwrap();
    n
}

/// Latest announcement_id (the row created by the welcome flow).
async fn latest_ann_id(db: &Db) -> u64 {
    let (id,): (u64,) = sqlx::query_as(
        "SELECT id FROM ntf_announcements \
         WHERE created_by = 'system' \
         ORDER BY id DESC LIMIT 1",
    )
    .fetch_one(&db.pool)
    .await
    .unwrap();
    id
}

#[tokio::test]
async fn welcome_idempotent_and_renders_template() {
    let h = common::spawn_db().await;
    let redis = redis_cli().await;
    let db = h.db;

    let event_id = Uuid::now_v7();
    let user_id = format!("test-user-{}", &event_id.to_string()[..8]);

    let created = ensure_welcome_for_user(
        &db.pool,
        &redis,
        db.outbox_repo.as_ref(),
        event_id,
        &user_id,
        &payload(&user_id, "Alice"),
        Utc::now(),
    )
    .await
    .unwrap();
    assert!(created, "first call should create the announcement");

    let list = db.list_for_user(user_id.clone()).await.unwrap();
    assert!(!list.is_empty(), "user should have at least one announcement");
    let last = list.first().unwrap();
    assert!(
        last.title.contains("Alice"),
        "template should render username: title={:?}",
        last.title
    );
}

#[tokio::test]
async fn welcome_enqueues_outbox_event_in_same_tx() {
    let h = common::spawn_db().await;
    let redis = redis_cli().await;
    let db = h.db;

    let event_id = Uuid::now_v7();
    let user_id = format!("test-user-ob-{}", &event_id.to_string()[..8]);

    let created = ensure_welcome_for_user(
        &db.pool,
        &redis,
        db.outbox_repo.as_ref(),
        event_id,
        &user_id,
        &payload(&user_id, "Bob"),
        Utc::now(),
    )
    .await
    .unwrap();
    assert!(created);

    let ann_id = latest_ann_id(&db).await;
    assert_eq!(
        outbox_count_for_announcement(&db, ann_id).await,
        1,
        "ensure_welcome_for_user must enqueue exactly one notification.announcement.published row"
    );
}

#[tokio::test]
async fn welcome_redelivery_does_not_double_enqueue_outbox() {
    let h = common::spawn_db().await;
    let redis = redis_cli().await;
    let db = h.db;

    let event_id = Uuid::now_v7();
    let user_id = format!("test-user-rd-{}", &event_id.to_string()[..8]);

    let first = ensure_welcome_for_user(
        &db.pool,
        &redis,
        db.outbox_repo.as_ref(),
        event_id,
        &user_id,
        &payload(&user_id, "Carol"),
        Utc::now(),
    )
    .await
    .unwrap();
    assert!(first);

    // redelivery: same event_id, same payload — should be absorbed by the
    // ntf_event_idempotency row and short-circuit before outbox enqueue.
    ensure_welcome_for_user(
        &db.pool,
        &redis,
        db.outbox_repo.as_ref(),
        event_id,
        &user_id,
        &payload(&user_id, "Carol"),
        Utc::now(),
    )
    .await
    .unwrap();

    let ann_id = latest_ann_id(&db).await;
    assert_eq!(
        outbox_count_for_announcement(&db, ann_id).await,
        1,
        "idempotency guard must prevent a second outbox enqueue"
    );
}