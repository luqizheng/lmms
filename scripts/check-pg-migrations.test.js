'use strict';

const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');
const { FORBIDDEN, WARN, stripCommentLines, scanSql, collectPgMigrations } = require('./check-pg-migrations');

const REPO_ROOT = path.resolve(__dirname, '..');

test('stripCommentLines removes -- lines but keeps executable ones', () => {
  const sql = [
    '-- 转换规则说明：AUTO_INCREMENT / ON DUPLICATE KEY',
    'CREATE TABLE t (id BIGINT);',
    '  -- 缩进的注释行',
    'ALTER TABLE t ADD COLUMN c BOOLEAN;',
  ].join('\n');
  const out = stripCommentLines(sql);
  assert.ok(out.includes('CREATE TABLE t'));
  assert.ok(!out.includes('AUTO_INCREMENT'));
  assert.ok(!out.includes('ON DUPLICATE'));
});

test('valid PG corpus passes with zero errors', () => {
  const corpus = fs.readFileSync(path.join(__dirname, 'fixtures', 'pg-sql-corpus.sql'), 'utf8');
  const { errors } = scanSql(corpus);
  assert.deepStrictEqual(errors, [], `合法 PG 语料不应报错: ${JSON.stringify(errors)}`);
});

test('each forbidden pattern is caught on an executable line', () => {
  const samples = {
    AUTO_INCREMENT: 'CREATE TABLE t (id BIGINT AUTO_INCREMENT);',
    'ON DUPLICATE KEY': 'INSERT INTO t VALUES (1) ON DUPLICATE KEY UPDATE c = 1;',
    'ON UPDATE CURRENT_TIMESTAMP': 'created_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,',
    UNSIGNED: 'tenant_id BIGINT UNSIGNED NOT NULL,',
    'TINYINT(': 'is_admin TINYINT(1) NOT NULL,',
    DATETIME: 'created_at DATETIME(3) NOT NULL,',
    'ENGINE=': ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;',
    'DEFAULT CHARSET': ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;',
    'UNIQUE KEY': 'UNIQUE KEY uk_t_event (event_id),',
    'INSERT IGNORE': 'INSERT IGNORE INTO t (id) VALUES (1);',
    'GROUP_CONCAT(': "SELECT GROUP_CONCAT(role_id) FROM t;",
    'DATABASE(': 'SELECT DATABASE();',
    'GET_LOCK(': 'SELECT GET_LOCK(?, 0);',
    'RELEASE_LOCK(': 'SELECT RELEASE_LOCK(?);',
    $$: 'CREATE FUNCTION f() RETURNS void AS $$ BEGIN END $$ LANGUAGE plpgsql;',
    'CREATE FUNCTION': 'CREATE FUNCTION f() RETURNS void AS $$ BEGIN END $$ LANGUAGE plpgsql;',
    'CREATE TRIGGER': 'CREATE TRIGGER trg BEFORE INSERT ON t FOR EACH ROW EXECUTE PROCEDURE f();',
    "COMMENT '": "name VARCHAR(64) COMMENT '用户名',",
  };
  for (const [key, line] of Object.entries(samples)) {
    const { errors } = scanSql(line);
    assert.ok(errors.length > 0, `样例必须命中禁令: ${key}`);
  }
});

test('comment lines mentioning forbidden words are not violations', () => {
  const sql = [
    '-- 转换规则：AUTO_INCREMENT -> IDENTITY；ON DUPLICATE KEY -> ON CONFLICT；',
    '-- DATETIME -> TIMESTAMPTZ；ENGINE/CHARSET 删除',
    'CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);',
  ].join('\n');
  const { errors } = scanSql(sql);
  assert.deepStrictEqual(errors, []);
});

test('TIMESTAMP(n) warns but does not fail', () => {
  const { errors, warnings } = scanSql('created_at TIMESTAMP(3) NOT NULL,');
  assert.strictEqual(errors.length, 0);
  assert.ok(warnings.length > 0);
});

test('FORBIDDEN patterns cover the plan checklist', () => {
  const msgs = FORBIDDEN.map(([, msg]) => msg).join('\n');
  for (const kw of ['ON CONFLICT', 'TIMESTAMPTZ', 'IDENTITY', 'STRING_AGG', 'current_schema', 'advisory']) {
    assert.ok(
      msgs.includes(kw),
      `禁令清单应给出 ${kw} 的去向说明（帮助写迁移的人一步到位）`,
    );
  }
});

test('collectPgMigrations only picks services/*/migrations/postgres', () => {
  const files = collectPgMigrations(REPO_ROOT);
  assert.ok(files.length >= 7, `5 服务 + token 2 + audit 应至少 7 个 PG 迁移文件，实际 ${files.length}`);
  for (const f of files) {
    assert.ok(
      f.includes(`${path.sep}migrations${path.sep}postgres${path.sep}`),
      `必须来自 postgres 迁移目录: ${f}`,
    );
    assert.ok(f.includes(`${path.sep}services${path.sep}`), `必须来自 services/: ${f}`);
  }
});
