#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');

/**
 * PG 迁移门禁：扫描各服务 `migrations/postgres` 目录下全部 `.sql`，
 * 禁止两类内容：
 *
 *  1. MySQL 残留语法（AUTO_INCREMENT / ON DUPLICATE KEY / DATETIME / ...）
 *     —— 它们在 PG 下要么报错、要么静默改变语义；
 *  2. 与迁移执行器不兼容的语法（`$$` dollar-quoted 块 / `DO 块` /
 *     `CREATE FUNCTION|TRIGGER`）—— 执行器先按 ASCII `;` 切分再剥离 `--`
 *     注释行，dollar-quoted 内的分号会被切坏。
 *
 * 判定口径与 `apply_script` 一致：**先剥离 `--` 注释行再检查**，
 * 因此迁移文件头部「转换规则说明」里提到这些关键词不构成违规
 * （与 token-service db.rs 静态门禁的 executable_sql 同款处理）。
 *
 * 设计：docs/superpowers/specs/2026-11-02-postgresql-service-layer-support-design.md §4
 * 计划：docs/superpowers/plans/2026-11-02-postgresql-service-layer-support.md Task S0
 */

const FORBIDDEN = [
  [/\bAUTO_INCREMENT\b/i, 'AUTO_INCREMENT → GENERATED BY DEFAULT AS IDENTITY'],
  [/\bON\s+DUPLICATE\s+KEY\b/i, 'ON DUPLICATE KEY → ON CONFLICT'],
  [/\bON\s+UPDATE\s+CURRENT_TIMESTAMP/i, 'ON UPDATE CURRENT_TIMESTAMP → 应用层维护'],
  [/\bUNSIGNED\b/i, 'UNSIGNED → BIGINT（去符号）'],
  [/\bTINYINT\s*\(/i, 'TINYINT(n) → BOOLEAN / SMALLINT'],
  [/\bDATETIME\b/i, 'DATETIME → TIMESTAMPTZ'],
  [/\bENGINE\s*=/i, 'ENGINE= → 删除'],
  [/\bDEFAULT\s+CHARSET\b/i, 'DEFAULT CHARSET → 删除'],
  [/\bCHARACTER\s+SET\s+\w+\./i, 'MySQL CHARACTER SET 限定 → 删除'],
  [/\bCOLLATE\s*=\s*\w+\./i, 'MySQL COLLATE 限定 → 删除'],
  [/\bUNIQUE\s+KEY\b/i, 'UNIQUE KEY → CREATE UNIQUE INDEX'],
  [/\bINSERT\s+IGNORE\b/i, 'INSERT IGNORE → ON CONFLICT DO NOTHING'],
  [/\bGROUP_CONCAT\s*\(/i, 'GROUP_CONCAT → STRING_AGG'],
  [/\bDATE_FORMAT\s*\(/i, 'DATE_FORMAT → TO_CHAR'],
  [/\bIFNULL\s*\(/i, 'IFNULL → COALESCE'],
  [/\bDATABASE\s*\(\s*\)/i, 'DATABASE() → current_schema()'],
  [/\bGET_LOCK\s*\(/i, 'GET_LOCK → pg_try_advisory_lock'],
  [/\bRELEASE_LOCK\s*\(/i, 'RELEASE_LOCK → pg_advisory_unlock'],
  [/\$\$/, '$$ dollar-quoted 块（split(\';\') 切分器不兼容）'],
  [/^\s*DO\s+\$/im, 'DO 块（split(\';\') 切分器不兼容）'],
  [/\bCREATE\s+(OR\s+REPLACE\s+)?(FUNCTION|TRIGGER|PROCEDURE)\b/i, 'FUNCTION/TRIGGER/PROCEDURE → 应用层维护'],
  [/\bCOMMENT\s+'/i, "列/表内联 COMMENT '...' → 丢弃或 COMMENT ON"],
];

/** 只告警不拦卡（需要人工确认的灰区）。 */
const WARN = [
  [/\bTIMESTAMP\s*\(/i, '裸 TIMESTAMP(n)？请确认是 TIMESTAMPTZ（DateTime<Utc> 唯一可解类型）'],
];

/**
 * 剥离 `--` 注释行（与迁移执行器 apply_script 同口径）。
 *
 * @param {string} sql SQL 文本。
 * @returns {string} 只含可执行行的文本。
 */
function stripCommentLines(sql) {
  return sql
    .split('\n')
    .filter((line) => !line.trimStart().startsWith('--'))
    .join('\n');
}

/**
 * 扫描一份 PG 迁移脚本，返回违规与告警。
 *
 * @param {string} sql 迁移文件内容（原始文本，含注释）。
 * @returns {{errors: Array<{line: number, pattern: RegExp, msg: string}>, warnings: Array<{line: number, msg: string}>}}
 */
function scanSql(sql) {
  const executable = stripCommentLines(sql);
  const errors = [];
  const warnings = [];
  const lines = executable.split('\n');
  for (const [pattern, msg] of FORBIDDEN) {
    lines.forEach((line, i) => {
      if (pattern.test(line)) errors.push({ line: i + 1, pattern, msg });
    });
  }
  for (const [pattern, msg] of WARN) {
    lines.forEach((line, i) => {
      if (pattern.test(line)) warnings.push({ line: i + 1, msg });
    });
  }
  return { errors, warnings };
}

/**
 * 递归收集目录下所有 `.sql` 文件。
 *
 * @param {string} dir 起始目录。
 * @param {string[]} acc 路径累加器。
 * @returns {string[]} 绝对路径列表。
 */
function walkSql(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory() && !entry.name.startsWith('.') && entry.name !== 'node_modules' && entry.name !== 'target') {
      walkSql(full, acc);
    } else if (entry.isFile() && entry.name.endsWith('.sql')) {
      acc.push(full);
    }
  }
  return acc;
}

/**
 * 列出仓内全部 PG 迁移文件（各服务 migrations/postgres 目录下的 .sql）。
 *
 * @param {string} repoRoot 仓库根。
 * @returns {string[]} 绝对路径列表。
 */
function collectPgMigrations(repoRoot) {
  return walkSql(path.join(repoRoot, 'services')).filter((f) =>
    f.includes(`${path.sep}migrations${path.sep}postgres${path.sep}`),
  );
}

/**
 * 门禁主体：违规即 exit 1，告警只打印不拦卡。
 *
 * @returns {Promise<void>}
 */
async function main() {
  const repoRoot = path.resolve(__dirname, '..');
  const files = collectPgMigrations(repoRoot);
  const errors = [];
  const warnings = [];

  for (const file of files) {
    const { errors: e, warnings: w } = scanSql(fs.readFileSync(file, 'utf8'));
    const rel = path.relative(repoRoot, file);
    e.forEach((x) => errors.push(`${rel}:${x.line} — ${x.msg}`));
    w.forEach((x) => warnings.push(`${rel}:${x.line} — ${x.msg}`));
  }

  for (const w of warnings) console.warn(`WARN: ${w}`);
  if (errors.length > 0) {
    console.error(`FAIL: ${errors.length} 处 PG 迁移残留/不兼容语法`);
    errors.forEach((e) => console.error(`  ${e}`));
    process.exit(1);
  }
  console.log(`PASS: ${files.length} 个 PG 迁移文件无 MySQL 残留语法`);
}

module.exports = { FORBIDDEN, WARN, stripCommentLines, scanSql, collectPgMigrations, main };

if (require.main === module) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
