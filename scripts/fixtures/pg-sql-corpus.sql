CREATE TABLE cfg_namespaces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL DEFAULT 1,
    "key" VARCHAR(255),
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    payload JSONB NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);

CREATE INDEX idx_cfg_namespaces_tenant ON cfg_namespaces (tenant_id);
CREATE UNIQUE INDEX uk_cfg_namespaces_key ON cfg_namespaces ("key");

